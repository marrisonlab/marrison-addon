'use strict';
// Isolated browser UI and anonymous, fresh-state hydration. No live WordPress writes.
const assert = require('node:assert/strict');
const path = require('node:path');
const {execFileSync} = require('node:child_process');
const {chromium} = require('playwright');
const wordpress = process.argv[2];
assert(wordpress, 'Pass an installed WordPress source root');
const base = path.join(__dirname, '../marrison-addon/includes/modules/business-info/assets');
const fixture = mode => execFileSync('php', [path.join(__dirname,'business-info-php-test.php'),wordpress,mode],{encoding:'utf8'});
const admin = JSON.parse(fixture('--fixture-admin'));
const emptyAdmin = JSON.parse(fixture('--fixture-admin-empty'));
const front = fixture('--fixture-front');
(async () => {
  const browser = await chromium.launch({channel:'chrome',headless:true});
  try {
    for (const width of [1280,390]) {
      const page = await browser.newPage({viewport:{width,height:1000}}), errors = [];
      page.on('pageerror', e => errors.push(e.message));
      await page.route('https://example.test/**', route => route.fulfill({contentType:'text/html',body:'<!doctype html><html lang="it"><head><meta charset="utf-8"></head><body>' + admin.html + '</body></html>'}));
      await page.goto('https://example.test/admin');
      await page.addStyleTag({content:'body{font:14px Arial;margin:12px}.button{padding:6px 12px}.screen-reader-text{position:absolute;width:1px;height:1px;overflow:hidden;clip-path:inset(50%)}'});
      await page.addStyleTag({path:path.join(wordpress,'wp-includes/css/dashicons.min.css')});
      await page.addStyleTag({path:path.join(wordpress,'wp-admin/css/forms.css')});
      await page.addStyleTag({path:path.join(base,'admin.css')});
      await page.evaluate(config => { window.marrisonBusinessInfoAdmin = config; window.confirm = () => true; document.getElementById('marrison-business-info-form').addEventListener('submit',e => e.preventDefault()); },admin.config);
      await page.addScriptTag({path:path.join(base,'admin.js')});
      assert(await page.getByRole('button',{name:'Salva Info Azienda'}).isEnabled());
      assert(await page.locator('#marrison-bi-completeness').textContent().then(t => t.includes('essenziali presenti')));
      await page.getByRole('tab',{name:'Privacy e titolare',exact:true}).click();
      const privacy = page.locator('#bi-panel-privacy');
      assert.equal(await privacy.getByLabel('Email usata nella policy',{exact:false}).inputValue(),'email_amministrazione');
      assert.equal(await privacy.getByLabel('Email usata nella policy',{exact:false}).locator('option').count(),3);
      assert(await privacy.locator('.bi-privacy-icon').count() >= 6);
      const controllerName = privacy.getByLabel('Titolare del trattamento — nome / ragione sociale',{exact:false});
      assert(await controllerName.isVisible(), 'Controller name requires a checkbox');
      await controllerName.fill('Mario Rossi');
      assert(await privacy.getByLabel('Email usata nella policy',{exact:false}).isVisible());
      assert(await page.locator('#marrison-bi-completeness').textContent().then(t => t.includes('essenziali presenti')));
      await page.getByRole('tab',{name:'Contatti',exact:true}).click();
      const contacts = page.locator('#bi-panel-contacts');
      assert(await contacts.getByLabel('Chiave univoca').first().isEditable() === false);
      await contacts.getByRole('button',{name:'Sposta giù',exact:true}).first().click();
      await page.getByRole('tab',{name:'Privacy e titolare',exact:true}).click();
      assert.equal(await privacy.getByLabel('Email usata nella policy',{exact:false}).inputValue(),'email_amministrazione','Reordering rebound privacy contact');
      await page.getByRole('tab',{name:'Contatti',exact:true}).click();
      await contacts.getByRole('button',{name:'Aggiungi recapito',exact:true}).click();
      const newRow = contacts.locator('.bi-record').last();
      await newRow.getByLabel('Etichetta',{exact:true}).fill('Email acquisti');
      await newRow.getByLabel('Chiave univoca').fill('email_acquisti');
      await newRow.getByLabel('Recapito',{exact:false}).fill('acquisti@example.test');
      await page.getByRole('tab',{name:'Privacy e titolare',exact:true}).click();
      await privacy.getByLabel('Email usata nella policy',{exact:false}).selectOption('email_acquisti');
      assert.equal(await controllerName.inputValue(),'Mario Rossi', 'Controller name lost on tab change');
      await privacy.getByLabel('Usa dati dedicati per il titolare',{exact:false}).check();
      assert(await page.locator('#marrison-bi-completeness').textContent().then(t => t.includes('essenziali presenti')), 'Empty overrides erased selected contacts');
      await controllerName.fill('Altro titolare');
      await privacy.getByLabel('Email del titolare',{exact:false}).fill('altro@example.test');
      await privacy.getByLabel('Indirizzo completo e Paese del titolare',{exact:false}).fill('Via Secondaria 2, Italia');
      await privacy.getByLabel('Usa dati dedicati per il titolare',{exact:false}).uncheck();
      assert(await controllerName.isVisible());
      assert.equal(await controllerName.inputValue(),'Altro titolare');
      await privacy.getByLabel('Usa dati dedicati per il titolare',{exact:false}).check();
      assert(await privacy.getByLabel('Responsabile protezione dati (DPO)',{exact:false}).isVisible());
      await page.getByRole('tab',{name:'Orari di apertura',exact:true}).click();
      const hours = page.locator('#bi-panel-hours'), monday = hours.locator('.bi-record').filter({has:page.getByRole('heading',{name:'Lunedì',exact:true})});
      await page.evaluate(() => { window.confirm = () => false; });
      await monday.getByRole('button',{name:'Applica a tutti',exact:true}).click();
      assert.equal(await page.evaluate(() => marrisonBusinessInfoAdmin.data.hours.weekly['7'].open),false,'Rejected overwrite changed hours');
      await page.evaluate(() => { window.confirm = () => true; });
      await monday.getByRole('button',{name:'Applica a tutti',exact:true}).click();
      await monday.getByLabel('Apertura',{exact:true}).first().fill('08:30');
      assert.equal(await page.evaluate(() => marrisonBusinessInfoAdmin.data.hours.weekly['2'].slots[0].start),'09:00','Copy shared a slot reference');
      assert.equal(await page.evaluate(() => marrisonBusinessInfoAdmin.data.hours.weekly['7'].slots[0].start),'09:00');
      await monday.getByRole('button',{name:'Applica ai feriali (Lun–Ven)',exact:true}).click();
      assert.equal(await page.evaluate(() => marrisonBusinessInfoAdmin.data.hours.weekly['5'].slots[0].start),'08:30');
      assert.equal(await page.evaluate(() => marrisonBusinessInfoAdmin.data.hours.weekly['7'].slots[0].start),'09:00');
      await monday.getByRole('button',{name:'Aggiungi fascia',exact:true}).click();
      assert.equal(await monday.getByLabel('Apertura',{exact:true}).count(),3);
      await monday.getByRole('button',{name:'Rimuovi fascia',exact:true}).last().click();
      await page.getByRole('button',{name:'Salva Info Azienda',exact:true}).click();
      const saved = JSON.parse(await page.locator('#marrison-business-info-payload').inputValue());
      assert.equal(saved.privacy.email_key,'email_acquisti');
      assert.equal(saved.privacy.controller_name,'Altro titolare');
      assert(!Object.hasOwn(saved.privacy,'email_value'));
      assert.equal(saved.hours.weekly['1'].slots[0].start,'08:30');
      assert(!await page.evaluate(() => document.documentElement.scrollWidth > innerWidth),'Admin overflows at ' + width);
      assert.deepEqual(errors,[]);
      if (process.env.BUSINESS_INFO_SCREENSHOTS) {
        await page.getByRole('tab',{name:'Privacy e titolare',exact:true}).click(); await page.evaluate(() => scrollTo(0,0));
        await page.screenshot({path:path.join(process.env.BUSINESS_INFO_SCREENSHOTS,'business-info-admin-' + width + '.png'),fullPage:true});
      }
      await page.close();
    }
    const fresh = await browser.newPage();
    await fresh.setContent(emptyAdmin.html);
    await fresh.evaluate(config => { window.marrisonBusinessInfoAdmin = config; document.getElementById('marrison-business-info-form').addEventListener('submit',e => e.preventDefault()); },emptyAdmin.config);
    await fresh.addScriptTag({path:path.join(base,'admin.js')});
    assert(await fresh.locator('#marrison-bi-completeness').textContent().then(t => t.includes('mancanti')));
    await fresh.getByLabel('Ragione sociale',{exact:false}).fill('Prima azienda');
    await fresh.getByRole('tab',{name:'Privacy e titolare',exact:true}).click();
    await fresh.getByLabel('Responsabile protezione dati (DPO)',{exact:false}).fill('Primo DPO');
    await fresh.getByRole('button',{name:'Salva Info Azienda',exact:true}).click();
    const firstSave = JSON.parse(await fresh.locator('#marrison-business-info-payload').inputValue());
    assert.equal(firstSave.company.legal_name,'Prima azienda','New-site company fields were lost in JSON serialization');
    assert.equal(firstSave.privacy.dpo,'Primo DPO','New-site privacy fields were lost in JSON serialization');
    await fresh.close();
    const page = await browser.newPage({viewport:{width:390,height:900}}), errors = [];
    page.on('pageerror',e => errors.push(e.message));
    let calls = 0, fail = false, state = 'pause';
    await page.route('https://example.test/**', route => {
      if (route.request().url().includes('admin-ajax.php')) {
        calls++;
        const params = new URL(route.request().url()).searchParams;
        assert.equal(params.get('action'),'marrison_business_hours');
        assert(params.has('_'),'Fresh-state URL lacks cache buster');
        return route.fulfill(fail ? {status:503,body:'Unavailable'} : {json:{success:true,data:{status:{state,refresh_in:1},text:state === 'pause' ? 'In pausa · Riapre alle 16:00' : 'Aperto ora · Chiude alle 20:00',value:'09:00–14:00 / 16:00–20:00',rows:[{label:'Lunedì–Venerdì',hours:'09:00–14:00 / 16:00–20:00'}],exceptions:[{label:'25/12/2026 · Festività',hours:'Chiuso'}]}}});
      }
      return route.fulfill({contentType:'text/html',body:'<!doctype html><html lang="it"><head><meta charset="utf-8"></head><body>' + front + '</body></html>'});
    });
    await page.goto('https://example.test/orari');
    assert.equal(await page.locator('[data-state="unknown"]').count(),2);
    await page.addStyleTag({path:path.join(base,'frontend.css')});
    await page.addScriptTag({path:path.join(base,'frontend.js')});
    await page.waitForFunction(() => document.querySelectorAll('[data-state="pause"]').length === 2);
    assert.equal(await page.locator('[data-marrison-business-hours]').last().textContent(),'09:00–14:00 / 16:00–20:00');
    assert.equal(await page.locator('.marrison-bh__rows .marrison-bh__row').count(),1);
    assert(await page.locator('.marrison-bh__exceptions').isVisible());
    state = 'open';
    await page.waitForFunction(() => document.querySelectorAll('[data-state="open"]').length === 2);
    fail = true;
    await page.waitForFunction(() => document.querySelectorAll('[data-state="unknown"]').length === 2);
    assert.equal(await page.locator('.marrison-bh__status-text').first().textContent(),'Stato non disponibile','Failure left a stale opening claim');
    assert(calls >= 6);
    assert.deepEqual(errors,[]);
    await page.close();
    console.log('PASS browser: desktop/mobile admin, privacy icons/selectors, stable keys/reorder, JSON save, independent day copies/confirmation, slots; cached placeholder, live refresh/transition/failure and date exceptions.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
